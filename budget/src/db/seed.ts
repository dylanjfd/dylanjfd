function rulesFrom(keywords: Record<number, string>): Omit<Rule, 'id'>[] {
  return Object.entries(keywords).flatMap(([categoryId, list]) =>
    list
      .split(',')
      .map((k) => normalizeLabel(k))
      .filter(Boolean)
      .map((pattern) => ({ pattern, categoryId: Number(categoryId), source: 'default' as const })),
  );
}

/** Un mot-clé n'appartient qu'à une catégorie : la première liste qui le cite l'emporte. */
function unique(rules: Omit<Rule, 'id'>[]): Omit<Rule, 'id'>[] {
  const seen = new Set<string>();
  return rules.filter((r) => !seen.has(r.pattern) && !!seen.add(r.pattern));
}

export const DEFAULT_RULES: Omit<Rule, 'id'>[] = unique([...rulesFrom(KEYWORDS), ...rulesFrom(KEYWORDS_V2)]);

/** Mots-clés apparus en version 2 (ceux de la version 1 que vous avez supprimés ne reviennent pas). */
export const RULES_ADDED_IN_V2: Omit<Rule, 'id'>[] = (() => {
  const v1 = new Set(rulesFrom(KEYWORDS).map((r) => r.pattern));
  return DEFAULT_RULES.filter((r) => !v1.has(r.pattern));
})();

